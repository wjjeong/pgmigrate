type env struct {
	src, tgt *pgx.Conn
	s        string
}

func setup(t *testing.T) *env {
	t.Helper()
	src, tgt := testutil.Source(t), testutil.Target(t)
	return &env{src: src, tgt: tgt, s: testutil.Schema(t, src, tgt)}
}

// sql replaces every "S." with the quoted test schema.
func (e *env) sql(q string) string {
	return strings.ReplaceAll(q, "S.", pgx.Identifier{e.s}.Sanitize()+".")
}

func (e *env) onSrc(t *testing.T, qs ...string) {
	t.Helper()
	for _, q := range qs {
		testutil.MustExec(t, e.src, e.sql(q))
	}
}

func (e *env) onTgt(t *testing.T, qs ...string) {
	t.Helper()
	for _, q := range qs {
		testutil.MustExec(t, e.tgt, e.sql(q))
	}
}

func (e *env) ref(name string) catalog.TableRef { return catalog.TableRef{Schema: e.s, Name: name} }

func (e *env) sel(mode plan.Mode, drop bool, names ...string) []plan.Selection {
	var out []plan.Selection
	for _, n := range names {
		out = append(out, plan.Selection{Ref: e.ref(n), Mode: mode, DropRecreate: drop})
	}
	return out
}

func (e *env) build(t *testing.T, tgtEnv string, sel ...plan.Selection) *plan.Plan {
	t.Helper()
	sc := config.Conn{Name: "src", Env: "dev", Host: "localhost", Port: 55432, Database: "postgres", User: "postgres"}
	tc := config.Conn{Name: "tgt", Env: tgtEnv, Host: "localhost", Port: 55433, Database: "postgres", User: "postgres"}
	p, err := plan.Build(context.Background(), e.src, e.tgt, sc, tc, sel)
	if err != nil {
		t.Fatal(err)
	}
	return p
}

func (e *env) mustPlan(t *testing.T, sel ...plan.Selection) *plan.Plan {
	t.Helper()
	p := e.build(t, "dev", sel...)
	if p.HasErrors() {
		t.Fatalf("계획 오류: %+v", p.Issues)
	}
	return p
}

func run(ctx context.Context, e *env, p *plan.Plan, opt Options, onEvent func(Event)) (*Result, error) {
	return Execute(ctx, e.src, e.tgt, p, opt, runlog.Discard(), onEvent)
}

func mustRun(t *testing.T, e *env, p *plan.Plan) *Result {
	t.Helper()
	res, err := run(context.Background(), e, p, Options{}, nil)
	if err != nil {
		t.Fatalf("Execute: %v", err)
	}
	if res == nil || !res.Committed {
		t.Fatalf("Committed가 아님: %+v", res)
	}
	return res
}

// rows returns every row of the query as text (NULL -> "<null>"), one string per row.
func rows(t *testing.T, c *pgx.Conn, q string) []string {
	t.Helper()
	rs, err := c.Query(context.Background(), q, pgx.QueryExecModeSimpleProtocol) // text 형식
	if err != nil {
		t.Fatalf("%v\n%s", err, q)
	}
	defer rs.Close()
	var out []string
	for rs.Next() {
		var parts []string
		for _, v := range rs.RawValues() {
			if v == nil {
				parts = append(parts, "<null>")
			} else {
				parts = append(parts, string(v))
			}
		}
		out = append(out, strings.Join(parts, "|"))
	}
	if err := rs.Err(); err != nil {
		t.Fatal(err)
	}
	return out
}

func one(t *testing.T, c *pgx.Conn, q string) string {
	t.Helper()
	r := rows(t, c, q)
	if len(r) != 1 {
		t.Fatalf("행 1개를 기대했으나 %d개: %s", len(r), q)
	}
	return r[0]
}

// fresh opens a new target connection; the one given to Execute may be closed after a failure.
func fresh(t *testing.T) *pgx.Conn { return testutil.Target(t) }

func TestExecute_Create(t *testing.T) {
	e := setup(t)
	e.onSrc(t,
		`CREATE TYPE S.mood AS ENUM ('sad','ok','happy')`,
		`CREATE TABLE S."Order" (
			id serial PRIMARY KEY,
			code varchar(20) NOT NULL UNIQUE,
			amt numeric(12,2) DEFAULT 0 CHECK (amt >= 0),
			nm text COLLATE "C",
			g int GENERATED ALWAYS AS (id*2) STORED,
			v int GENERATED ALWAYS AS (id+1) VIRTUAL,
			parent_id int REFERENCES S."Order"(id))`,
		`CREATE INDEX idx_nm ON S."Order" (nm)`,
		`COMMENT ON TABLE S."Order" IS '주문'`,
		`INSERT INTO S."Order" (code, amt, nm, parent_id) VALUES ('a', 1, 'x', NULL), ('b', 2, 'y', 1), ('c', 3, NULL, 2)`,
		`SELECT nextval(pg_get_serial_sequence('S."Order"', 'id'))`, // 소스 시퀀스 값 4
		`CREATE TABLE S.공통코드 (
			id int GENERATED BY DEFAULT AS IDENTITY (START 100 INCREMENT 5),
			st S.mood)`,
		`INSERT INTO S.공통코드 (st) VALUES ('ok'), ('happy')`,
		`CREATE TABLE S.always_id (id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY, x text)`,
		`INSERT INTO S.always_id (x) VALUES ('one'), ('two'), ('three')`,
		`DELETE FROM S.always_id WHERE id = 2`,
	)
	e.onTgt(t, `CREATE TYPE S.mood AS ENUM ('sad','ok','happy')`)

	var sel []plan.Selection
	sel = append(sel, e.sel(plan.ModeCreate, false, "Order", "공통코드", "always_id")...)
	p := e.mustPlan(t, sel...)
	res := mustRun(t, e, p)

	if len(res.Tables) != 3 {
		t.Fatalf("Tables: %+v", res.Tables)
	}
	for _, tr := range res.Tables {
		if tr.Mode != plan.ModeCreate || tr.Before != 0 || tr.SourceRows != tr.After {
			t.Errorf("TableResult: %+v", tr)
		}
	}
	queries := []string{
		`SELECT id, code, amt, nm, g, v, parent_id FROM S."Order" ORDER BY id`,
		`SELECT id, st FROM S.공통코드 ORDER BY id`,
		`SELECT id, x FROM S.always_id ORDER BY id`,
		`SELECT obj_description('S."Order"'::regclass, 'pg_class')`,
		fmt.Sprintf(`SELECT count(*) FROM pg_indexes WHERE schemaname = '%s' AND indexname = 'idx_nm'`, e.s),
	}
	for _, q := range queries {
		if got, want := rows(t, e.tgt, e.sql(q)), rows(t, e.src, e.sql(q)); !reflect.DeepEqual(got, want) {
			t.Errorf("%s\n got: %q\nwant: %q", q, got, want)
		}
	}
	if got := rows(t, e.tgt, e.sql(`SELECT id, x FROM S.always_id ORDER BY id`)); !reflect.DeepEqual(got, []string{"1|one", "3|three"}) {
		t.Errorf("identity ALWAYS 값: %q", got)
	}
	for _, q := range []string{
		`SELECT nextval(pg_get_serial_sequence('S."Order"', 'id'))`,
		`SELECT nextval(pg_get_serial_sequence('S.공통코드', 'id'))`,
		`SELECT nextval(pg_get_serial_sequence('S.always_id', 'id'))`,
	} {
		if got, want := one(t, e.tgt, e.sql(q)), one(t, e.src, e.sql(q)); got != want {
			t.Errorf("%s: 타깃 %s, 소스 %s", q, got, want)
		}
	}
	// FK도 만들어졌다.
	if got := one(t, e.tgt, e.sql(`SELECT count(*) FROM pg_constraint WHERE conrelid = 'S."Order"'::regclass AND contype = 'f'`)); got != "1" {
		t.Errorf("FK 개수: %s", got)
	}
}

