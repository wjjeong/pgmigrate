// assertGoroutines fails if goroutines started during the test are still running.
func assertGoroutines(t *testing.T, before int) {
	t.Helper()
	deadline := time.Now().Add(2 * time.Second)
	for {
		n := runtime.NumGoroutine()
		if n <= before {
			return
		}
		if time.Now().After(deadline) {
			t.Errorf("고루틴 누수: 시작 %d, 끝 %d", before, n)
			return
		}
		time.Sleep(10 * time.Millisecond)
	}
}

func TestExecute_AppendConflictRollsBack(t *testing.T) {
	e := setup(t)
	e.onSrc(t,
		`CREATE TABLE S.a_first (id int PRIMARY KEY)`,
		`INSERT INTO S.a_first VALUES (100)`,
		`CREATE TABLE S.b_conf (id serial PRIMARY KEY, v text)`,
		`INSERT INTO S.b_conf (v) VALUES ('a'), ('b'), ('c')`,
		`SELECT setval(pg_get_serial_sequence('S.b_conf', 'id'), 500)`,
		`CREATE TABLE S.c_new (id serial PRIMARY KEY)`,
		`INSERT INTO S.c_new DEFAULT VALUES`,
	)
	e.onTgt(t,
		`CREATE TABLE S.a_first (id int PRIMARY KEY)`,
		`INSERT INTO S.a_first VALUES (1), (2), (3), (4)`,
		`CREATE TABLE S.b_conf (id serial PRIMARY KEY, v text)`,
		`INSERT INTO S.b_conf (v) VALUES ('old')`, // id 1 → 충돌
	)
	sel := append(e.sel(plan.ModeTruncate, false, "a_first"), e.sel(plan.ModeAppend, false, "b_conf")...)
	sel = append(sel, e.sel(plan.ModeCreate, false, "c_new")...)
	p := e.mustPlan(t, sel...)
	if p.Steps[0].Sel.Ref.Name != "a_first" {
		t.Fatalf("순서: %+v", p.Steps)
	}
	before := runtime.NumGoroutine()
	var events []Event
	res, err := run(context.Background(), e, p, Options{}, func(ev Event) { events = append(events, ev) })
	var pgErr *pgconn.PgError
	if !errors.As(err, &pgErr) || pgErr.Code != "23505" {
		t.Fatalf("PK 충돌 오류를 기대했습니다: %v", err)
	}
	if !strings.Contains(err.Error(), e.ref("b_conf").String()) || !strings.Contains(err.Error(), string(PhaseCopy)) {
		t.Errorf("오류 형식: %v", err)
	}
	if res == nil || res.Committed {
		t.Errorf("Result: %+v", res)
	}
	if last := events[len(events)-1]; last.Phase != PhaseFailed || last.Err == nil {
		t.Errorf("마지막 이벤트: %+v", last)
	}
	assertGoroutines(t, before)

	c := fresh(t)
	if got := rows(t, c, e.sql(`SELECT id FROM S.a_first ORDER BY id`)); !reflect.DeepEqual(got, []string{"1", "2", "3", "4"}) {
		t.Errorf("a_first가 원래대로가 아닙니다: %q", got)
	}
	if got := rows(t, c, e.sql(`SELECT id, v FROM S.b_conf`)); !reflect.DeepEqual(got, []string{"1|old"}) {
		t.Errorf("b_conf가 원래대로가 아닙니다: %q", got)
	}
	if got := one(t, c, e.sql(`SELECT last_value FROM S.b_conf_id_seq`)); got != "1" {
		t.Errorf("시퀀스가 바뀌었습니다: %s", got)
	}
	if got := one(t, c, e.sql(`SELECT to_regclass('S.c_new') IS NULL`)); got != "t" {
		t.Errorf("c_new가 남아 있습니다")
	}
}

