//go:build integration

package ddl

import (
	"context"
	"fmt"
	"reflect"
	"testing"

	"pgmigrate/internal/catalog"
	"pgmigrate/internal/testutil"
)

// 소스에 Task 3 픽스처(상속 child 제외)를 만들고, ddl이 만든 DDL을 타깃에 실행해
// 구조가 같은지 비교한다.
func TestRoundTrip(t *testing.T) {
	src := testutil.Source(t)
	tgt := testutil.Target(t)
	s := testutil.Schema(t, src, tgt)

	for _, sql := range []string{
		fmt.Sprintf(`CREATE TYPE %s.mood AS ENUM ('sad','ok','happy')`, s),
		fmt.Sprintf(`CREATE TABLE %s."Order" (
			id serial PRIMARY KEY,
			code varchar(20) NOT NULL UNIQUE,
			amt numeric(12,2) DEFAULT 0 CHECK (amt >= 0),
			nm text COLLATE "C",
			g int GENERATED ALWAYS AS (id*2) STORED,
			v int GENERATED ALWAYS AS (id+1) VIRTUAL,
			parent_id int REFERENCES %s."Order"(id))`, s, s),
		fmt.Sprintf(`CREATE INDEX idx_nm ON %s."Order" (nm)`, s),
		fmt.Sprintf(`COMMENT ON TABLE %s."Order" IS '주문 it''s'`, s),
		fmt.Sprintf(`COMMENT ON COLUMN %s."Order".code IS '코드'`, s),
		fmt.Sprintf(`CREATE FUNCTION %s.trg() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END $$`, s),
		fmt.Sprintf(`CREATE TRIGGER t1 BEFORE INSERT ON %s."Order" FOR EACH ROW EXECUTE FUNCTION %s.trg()`, s, s),
		fmt.Sprintf(`CREATE TABLE %s.공통코드 (
			id int GENERATED BY DEFAULT AS IDENTITY (START 100 INCREMENT 5),
			st %s.mood)`, s, s),
		fmt.Sprintf(`SELECT nextval(pg_get_serial_sequence('%s.공통코드', 'id')), nextval(pg_get_serial_sequence('%s.공통코드', 'id'))`, s, s),
	} {
		testutil.MustExec(t, src, sql)
	}
	// enum은 이 도구가 만들지 않으므로 타깃에 미리 만든다.
	testutil.MustExec(t, tgt, fmt.Sprintf(`CREATE TYPE %s.mood AS ENUM ('sad','ok','happy')`, s))

	ctx := context.Background()
	names := []string{"Order", "공통코드"}
	var srcTabs []*catalog.Table
	for _, n := range names {
		tb, err := catalog.Describe(ctx, src, catalog.TableRef{Schema: s, Name: n})
		if err != nil {
			t.Fatal(err)
		}
		srcTabs = append(srcTabs, tb)
		for _, sql := range CreateTable(tb) {
			testutil.MustExec(t, tgt, sql)
		}
	}
	for _, tb := range srcTabs {
		for _, sql := range ForeignKeys(tb) {
			testutil.MustExec(t, tgt, sql)
		}
	}

	for _, want := range srcTabs {
		got, err := catalog.Describe(ctx, tgt, want.Ref)
		if err != nil {
			t.Fatal(err)
		}
		if !reflect.DeepEqual(got.Columns, want.Columns) {
			t.Errorf("%s Columns\n got: %+v\nwant: %+v", want.Ref, got.Columns, want.Columns)
		}
		if !reflect.DeepEqual(got.Constraints, want.Constraints) {
			t.Errorf("%s Constraints\n got: %+v\nwant: %+v", want.Ref, got.Constraints, want.Constraints)
		}
		if !reflect.DeepEqual(got.Indexes, want.Indexes) {
			t.Errorf("%s Indexes\n got: %+v\nwant: %+v", want.Ref, got.Indexes, want.Indexes)
		}
		if got.Comment != want.Comment || got.Unlogged != want.Unlogged {
			t.Errorf("%s Comment/Unlogged: %q/%v vs %q/%v", want.Ref, got.Comment, got.Unlogged, want.Comment, want.Unlogged)
		}
		// LastValue/IsCalled는 데이터 복사 후 SetSequence로 맞추는 값이라 DDL 왕복 대상이 아니다
		// (소스는 nextval이 호출됐고 타깃은 새 시퀀스다). 나머지 옵션만 비교한다.
		strip := func(in []catalog.Sequence) []catalog.Sequence {
			out := append([]catalog.Sequence(nil), in...)
			for i := range out {
				out[i].LastValue, out[i].IsCalled = 0, false
			}
			return out
		}
		if !reflect.DeepEqual(strip(got.Sequences), strip(want.Sequences)) {
			t.Errorf("%s Sequences\n got: %+v\nwant: %+v", want.Ref, got.Sequences, want.Sequences)
		}
		if got.TriggerCount != 0 {
			t.Errorf("%s TriggerCount = %d, 0 기대", want.Ref, got.TriggerCount)
		}
	}
	if len(srcTabs[0].Sequences) != 1 || len(srcTabs[1].Sequences) != 1 || srcTabs[0].TriggerCount != 1 {
		t.Fatalf("픽스처가 비어 있음: %+v", srcTabs)
	}
}
