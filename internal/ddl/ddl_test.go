func eq(t *testing.T, got, want []string) {
	t.Helper()
	if len(got) != len(want) {
		t.Fatalf("문 개수 %d != %d\n got: %q\nwant: %q", len(got), len(want), got, want)
	}
	for i := range got {
		if got[i] != want[i] {
			t.Errorf("[%d]\n got: %s\nwant: %s", i, got[i], want[i])
		}
	}
}

func TestCreateTable_Serial(t *testing.T) {
	tb := &catalog.Table{
		Ref: catalog.TableRef{Schema: "s", Name: "t"},
		Columns: []catalog.Column{
			{Name: "id", Type: "integer", NotNull: true, Default: "nextval('s.t_id_seq'::regclass)"},
			{Name: "code", Type: "character varying(20)", NotNull: true, Collation: `"C"`},
		},
		Constraints: []catalog.Constraint{{Name: "t_pkey", Type: 'p', Def: "PRIMARY KEY (id)"}},
		Indexes:     []catalog.Index{{Name: "idx_code", Def: "CREATE INDEX idx_code ON s.t USING btree (code)"}},
		Sequences: []catalog.Sequence{{Ref: catalog.TableRef{Schema: "s", Name: "t_id_seq"}, Column: "id",
			DataType: "integer", Start: 1, Increment: 1, Min: 1, Max: 2147483647, Cache: 1}},
	}
	eq(t, CreateTable(tb), []string{
		`CREATE SEQUENCE "s"."t_id_seq" AS integer START WITH 1 INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 CACHE 1 NO CYCLE`,
		`CREATE TABLE "s"."t" (` +
			`"id" integer DEFAULT nextval('s.t_id_seq'::regclass) NOT NULL, ` +
			`"code" character varying(20) COLLATE "C" NOT NULL, ` +
			`CONSTRAINT "t_pkey" PRIMARY KEY (id))`,
		`ALTER SEQUENCE "s"."t_id_seq" OWNED BY "s"."t"."id"`,
		`CREATE INDEX idx_code ON s.t USING btree (code)`,
	})
}

func TestCreateTable_Identity(t *testing.T) {
	tb := &catalog.Table{
		Ref: catalog.TableRef{Schema: "s", Name: "t"},
		Columns: []catalog.Column{
			{Name: "a", Type: "integer", NotNull: true, Identity: 'd'},
			{Name: "b", Type: "bigint", NotNull: true, Identity: 'a'},
		},
		Sequences: []catalog.Sequence{
			{Ref: catalog.TableRef{Schema: "s", Name: "t_a_seq"}, Column: "a", Identity: true, DataType: "integer",
				Start: 100, Increment: 5, Min: 1, Max: 2147483647, Cache: 1},
			{Ref: catalog.TableRef{Schema: "s", Name: "t_b_seq"}, Column: "b", Identity: true, DataType: "bigint",
				Start: 1, Increment: 1, Min: 1, Max: 9223372036854775807, Cache: 10, Cycle: true},
		},
	}
	got := CreateTable(tb)
	eq(t, got, []string{
		`CREATE TABLE "s"."t" (` +
			`"a" integer GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME "s"."t_a_seq" START WITH 100 INCREMENT BY 5 MINVALUE 1 MAXVALUE 2147483647 CACHE 1 NO CYCLE), ` +
			`"b" bigint GENERATED ALWAYS AS IDENTITY (SEQUENCE NAME "s"."t_b_seq" START WITH 1 INCREMENT BY 1 MINVALUE 1 MAXVALUE 9223372036854775807 CACHE 10 CYCLE))`,
	})
	if strings.Contains(strings.Join(got, "\n"), "CREATE SEQUENCE") {
		t.Error("identity에는 CREATE SEQUENCE가 없어야 한다")
	}
}

func TestCreateTable_Generated(t *testing.T) {
	tb := &catalog.Table{
		Ref: catalog.TableRef{Schema: "s", Name: "t"},
		Columns: []catalog.Column{
			{Name: "g", Type: "integer", Generated: 's', GeneratedExpr: "(id * 2)"},
			{Name: "v", Type: "integer", Generated: 'v', GeneratedExpr: "(id + 1)", NotNull: true},
		},
		Unlogged: true,
	}
	eq(t, CreateTable(tb), []string{
		`CREATE UNLOGGED TABLE "s"."t" (` +
			`"g" integer GENERATED ALWAYS AS ((id * 2)) STORED, ` +
			`"v" integer GENERATED ALWAYS AS ((id + 1)) VIRTUAL NOT NULL)`,
	})
}

func TestCreateTable_QuotedNames(t *testing.T) {
	tb := &catalog.Table{
		Ref:     catalog.TableRef{Schema: "My Schema", Name: "Order"},
		Columns: []catalog.Column{{Name: "user", Type: "text"}},
	}
	eq(t, CreateTable(tb), []string{`CREATE TABLE "My Schema"."Order" ("user" text)`})
	tb = &catalog.Table{
		Ref:     catalog.TableRef{Schema: "s", Name: "공통코드"},
		Columns: []catalog.Column{{Name: "코드", Type: "text"}},
	}
	eq(t, CreateTable(tb), []string{`CREATE TABLE "s"."공통코드" ("코드" text)`})
}

func TestCreateTable_ExcludesFK(t *testing.T) {
	tb := &catalog.Table{
		Ref:     catalog.TableRef{Schema: "s", Name: "t"},
		Columns: []catalog.Column{{Name: "id", Type: "integer"}, {Name: "p", Type: "integer"}},
		Constraints: []catalog.Constraint{
			{Name: "t_fk", Type: 'f', Def: "FOREIGN KEY (p) REFERENCES s.t(id)", RefTable: &catalog.TableRef{Schema: "s", Name: "t"}},
			{Name: "t_pk", Type: 'p', Def: "PRIMARY KEY (id)"},
		},
	}
	eq(t, CreateTable(tb), []string{`CREATE TABLE "s"."t" ("id" integer, "p" integer, CONSTRAINT "t_pk" PRIMARY KEY (id))`})
	eq(t, ForeignKeys(tb), []string{`ALTER TABLE "s"."t" ADD CONSTRAINT "t_fk" FOREIGN KEY (p) REFERENCES s.t(id)`})
}

func TestComment_Escaping(t *testing.T) {
	tb := &catalog.Table{
		Ref:     catalog.TableRef{Schema: "s", Name: "t"},
		Comment: "it's",
		Columns: []catalog.Column{{Name: "c", Type: "text", Comment: `a\b 'x'`}},
	}
	eq(t, CreateTable(tb), []string{
		`CREATE TABLE "s"."t" ("c" text)`,
		`COMMENT ON TABLE "s"."t" IS 'it''s'`,
		`COMMENT ON COLUMN "s"."t"."c" IS 'a\b ''x'''`,
	})
}

func TestDropTable(t *testing.T) {
	if got := DropTable(catalog.TableRef{Schema: "s", Name: "Order"}); got != `DROP TABLE "s"."Order"` {
		t.Error(got)
	}
}

func TestSetSequence(t *testing.T) {
	got := SetSequence(catalog.TableRef{Schema: "s", Name: "t_id_seq"}, 105, true)
	if want := `SELECT setval('"s"."t_id_seq"'::regclass, 105, true)`; got != want {
		t.Errorf("got %s want %s", got, want)
	}
	got = SetSequence(catalog.TableRef{Schema: "s", Name: "x"}, 1, false)
	if want := `SELECT setval('"s"."x"'::regclass, 1, false)`; got != want {
		t.Errorf("got %s want %s", got, want)
	}
}
