func describeFixture(t *testing.T) (Querier, string) {
	t.Helper()
	src := testutil.Source(t)
	s := testutil.Schema(t, src)
	for _, sql := range []string{
		fmt.Sprintf(`CREATE TYPE %s.mood AS ENUM ('sad','ok','happy')`, s),
		fmt.Sprintf(`CREATE TABLE %s."Order" (
			id serial PRIMARY KEY,
			code varchar(20) NOT NULL UNIQUE,
			amt numeric(12,2) DEFAULT 0 CHECK (amt >= 0),
			nm text COLLATE "C",
			g int GENERATED ALWAYS AS (id*2) STORED,
			v int GENERATED ALWAYS AS (id+1) VIRTUAL,
			parent_id int REFERENCES %s."Order"(id))`, s, s),
		fmt.Sprintf(`CREATE INDEX idx_nm ON %s."Order" (nm)`, s),
		fmt.Sprintf(`COMMENT ON TABLE %s."Order" IS '주문'`, s),
		fmt.Sprintf(`COMMENT ON COLUMN %s."Order".code IS '코드'`, s),
		fmt.Sprintf(`CREATE FUNCTION %s.trg() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END $$`, s),
		fmt.Sprintf(`CREATE TRIGGER t1 BEFORE INSERT ON %s."Order" FOR EACH ROW EXECUTE FUNCTION %s.trg()`, s, s),
		fmt.Sprintf(`CREATE TABLE %s.공통코드 (
			id int GENERATED BY DEFAULT AS IDENTITY (START 100 INCREMENT 5),
			st %s.mood)`, s, s),
		fmt.Sprintf(`SELECT nextval(pg_get_serial_sequence('%s.공통코드', 'id')), nextval(pg_get_serial_sequence('%s.공통코드', 'id'))`, s, s),
		fmt.Sprintf(`CREATE TABLE %s.child () INHERITS (%s."Order")`, s, s),
	} {
		testutil.MustExec(t, src, sql)
	}
	return src, s
}

func mustDescribe(t *testing.T, q Querier, s, name string) *Table {
	t.Helper()
	tb, err := Describe(context.Background(), q, TableRef{s, name})
	if err != nil {
		t.Fatal(err)
	}
	return tb
}

func TestDescribe_Columns(t *testing.T) {
	q, s := describeFixture(t)
	tb := mustDescribe(t, q, s, "Order")
	cols := map[string]Column{}
	var names []string
	for _, c := range tb.Columns {
		cols[c.Name] = c
		names = append(names, c.Name)
	}
	if got := strings.Join(names, ","); got != "id,code,amt,nm,g,v,parent_id" {
		t.Fatalf("컬럼 순서: %s", got)
	}
	if c := cols["id"]; !strings.Contains(c.Default, "nextval(") || !c.NotNull {
		t.Errorf("id: %+v", c)
	}
	if c := cols["code"]; c.Type != "character varying(20)" || !c.NotNull || c.Comment != "코드" {
		t.Errorf("code: %+v", c)
	}
	if c := cols["amt"]; c.Type != "numeric(12,2)" || c.Default != "0" || c.NotNull {
		t.Errorf("amt: %+v", c)
	}
	if c := cols["nm"]; c.Collation != `"C"` {
		t.Errorf("nm collation: %q", c.Collation)
	}
	if c := cols["code"]; c.Collation != "" {
		t.Errorf("code collation: %q", c.Collation)
	}
	if c := cols["g"]; c.Generated != 's' || c.Default != "" || c.GeneratedExpr == "" {
		t.Errorf("g: %+v", c)
	}
	if c := cols["v"]; c.Generated != 'v' || c.Default != "" || c.GeneratedExpr == "" {
		t.Errorf("v: %+v", c)
	}
	if c := cols["id"]; c.UserType || c.TypeSchema != "pg_catalog" || c.TypeName != "int4" || c.TypeKind != 'b' {
		t.Errorf("id type: %+v", c)
	}

	tb2 := mustDescribe(t, q, s, "공통코드")
	for _, c := range tb2.Columns {
		switch c.Name {
		case "st":
			if !c.UserType || c.TypeKind != 'e' || c.TypeSchema != s || c.TypeName != "mood" {
				t.Errorf("st: %+v", c)
			}
		case "id":
			if c.Identity != 'd' {
				t.Errorf("id identity: %+v", c)
			}
		}
	}
}

func TestDescribe_Constraints(t *testing.T) {
	q, s := describeFixture(t)
	tb := mustDescribe(t, q, s, "Order")
	types := map[byte]int{}
	for _, c := range tb.Constraints {
		types[c.Type]++
		if c.Type == 'f' {
			if c.RefTable == nil || *c.RefTable != (TableRef{s, "Order"}) {
				t.Errorf("FK RefTable: %+v", c.RefTable)
			}
		} else if c.RefTable != nil {
			t.Errorf("비 FK의 RefTable: %+v", c)
		}
		if c.Def == "" {
			t.Errorf("Def 비어 있음: %+v", c)
		}
	}
	if len(tb.Constraints) != 4 || types['p'] != 1 || types['u'] != 1 || types['c'] != 1 || types['f'] != 1 {
		t.Fatalf("제약조건: %+v", tb.Constraints)
	}
	for i := 1; i < len(tb.Constraints); i++ {
		if tb.Constraints[i-1].Name > tb.Constraints[i].Name {
			t.Errorf("이름 순서 위반")
		}
	}
}

func TestDescribe_Indexes(t *testing.T) {
	q, s := describeFixture(t)
	tb := mustDescribe(t, q, s, "Order")
	if len(tb.Indexes) != 1 || tb.Indexes[0].Name != "idx_nm" || !strings.Contains(tb.Indexes[0].Def, "CREATE INDEX") {
		t.Fatalf("인덱스: %+v", tb.Indexes)
	}
}

func TestDescribe_Sequences(t *testing.T) {
	q, s := describeFixture(t)
	tb := mustDescribe(t, q, s, "Order")
	if len(tb.Sequences) != 1 {
		t.Fatalf("serial 시퀀스 1개 기대: %+v", tb.Sequences)
	}
	sq := tb.Sequences[0]
	if sq.Identity || sq.Column != "id" || sq.Ref.Schema != s || sq.DataType != "integer" || sq.Increment != 1 || sq.Start != 1 || sq.IsCalled {
		t.Errorf("serial: %+v", sq)
	}

	tb2 := mustDescribe(t, q, s, "공통코드")
	if len(tb2.Sequences) != 1 {
		t.Fatalf("identity 시퀀스 1개 기대: %+v", tb2.Sequences)
	}
	sq = tb2.Sequences[0]
	if !sq.Identity || sq.Column != "id" || sq.Start != 100 || sq.Increment != 5 || sq.LastValue != 105 || !sq.IsCalled {
		t.Errorf("identity: %+v", sq)
	}
}

func TestDescribe_Flags(t *testing.T) {
	q, s := describeFixture(t)
	tb := mustDescribe(t, q, s, "Order")
	if tb.TriggerCount != 1 || tb.Comment != "주문" || !tb.Inherits || tb.Unlogged || tb.Partitioned || tb.IsPartition || tb.HasRLS {
		t.Errorf("Order flags: %+v", tb)
	}
	if ch := mustDescribe(t, q, s, "child"); !ch.Inherits {
		t.Errorf("child.Inherits=false")
	}
	if g := mustDescribe(t, q, s, "공통코드"); g.Inherits || g.TriggerCount != 0 {
		t.Errorf("공통코드 flags: %+v", g)
	}
}

func TestDescribe_NotFound(t *testing.T) {
	q, s := describeFixture(t)
	_, err := Describe(context.Background(), q, TableRef{s, "nope"})
	if !errors.Is(err, ErrNotFound) {
		t.Fatalf("ErrNotFound 기대: %v", err)
	}
}
